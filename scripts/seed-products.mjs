/**
 * Writes db/seed-products.sql from the JSON records in src/content/components.
 * Idempotent: INSERT OR IGNORE never overwrites a row the admin has edited.
 * Run: node scripts/seed-products.mjs
 * Then: npx wrangler d1 execute electronics-sourcing-db --local --file db/seed-products.sql
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const catalogDir = path.join(root, "src/content/components");
const assetsDir = path.join(root, "src/assets");
const out = path.join(root, "db/seed-products.sql");

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;

function assetRef(src) {
  const absolute = path.resolve(catalogDir, src);
  const relative = path.relative(assetsDir, absolute).split(path.sep).join("/");
  if (relative.startsWith("..")) throw new Error(`Image outside src/assets: ${src}`);
  return `asset:${relative}`;
}

const names = (await readdir(catalogDir)).filter((name) => name.endsWith(".json")).sort();
const lines = ["-- Generated by scripts/seed-products.mjs. Safe to run again.", ""];

for (const [index, name] of names.entries()) {
  const record = JSON.parse(await readFile(path.join(catalogDir, name), "utf8"));
  const data = {
    ...record,
    ...(record.images ? { images: record.images.map((image) => ({ ...image, src: assetRef(image.src) })) } : {}),
  };
  lines.push(
    `INSERT OR IGNORE INTO products (part_number, category, price, published, sort_order, data) VALUES (${quote(record.part_number)}, ${quote(record.category)}, ${record.price}, 1, ${index}, ${quote(JSON.stringify(data))});`,
    `INSERT OR IGNORE INTO stock (part_number, qty) VALUES (${quote(record.part_number)}, ${record.stock_qty});`,
  );
}

await writeFile(out, `${lines.join("\n")}\n`);
console.log(`Wrote ${path.relative(root, out)} with ${names.length} products.`);
